//! Fixed test vectors: what ZOKA's formats produce for fixed inputs.
//!
//! Reviewers and other implementations can compare byte for byte, and an
//! accidental change to a format before the genesis breaks this test instead
//! of a network. The expected values are in `tests/vectors/quantic-v1.txt`.
//! After a deliberate format change, regenerate them with
//! `ZOKA_WRITE_VECTORS=1 cargo test --test vectors` and review the diff.

use std::fmt::Write as _;

use orchard::keys::Scope;
use orchard::note::{ExtractedNoteCommitment, Nullifier, RandomSeed, Rho};
use orchard::value::{NoteValue, ValueCommitTrapdoor, ValueCommitment};
use orchard::{Note, NoteVersion};
use rand::rngs::StdRng;
use rand::SeedableRng;
use zoka_quantic::builder::build_coinbase;
use zoka_quantic::note_encryption::{encrypt_note, try_note_decryption, MEMO_SIZE};
use zoka_quantic::state::PREMINE_ATOMS;
use zoka_quantic::verify::proving_key;
use zoka_quantic::{Network, QuanticAddress, QuanticSpendingKey};

const VECTORS: &str = "tests/vectors/quantic-v1.txt";
const ROOT: [u8; 32] = [0x07; 32];

mod hex {
    pub fn encode(bytes: impl AsRef<[u8]>) -> String {
        bytes.as_ref().iter().map(|b| format!("{b:02x}")).collect()
    }
}

fn hash(bytes: &[u8]) -> String {
    hex::encode(blake2b_simd::Params::new().hash_length(32).hash(bytes).as_bytes())
}

fn short(network: Network) -> &'static str {
    match network {
        Network::Mainnet => "mainnet",
        Network::Testnet => "testnet",
        Network::Regtest => "regtest",
    }
}

fn generate() -> String {
    let mut out = String::new();
    writeln!(out, "# Zoka Quantic test vectors, format v1.").unwrap();
    writeln!(out, "# Generated by crates/zoka-quantic/tests/vectors.rs; hex is lowercase.").unwrap();
    writeln!(out, "# blake2b-256 below means BLAKE2b with 32-byte output and no key or personalization.").unwrap();

    // Keys and addresses: the same root on every network.
    for network in Network::ALL {
        let sk = QuanticSpendingKey::from_root(&ROOT, network, 0).unwrap();
        let fvk = sk.full_viewing_key();
        writeln!(out, "\n[keys.{}]", short(network)).unwrap();
        writeln!(out, "chain_id = {network}").unwrap();
        writeln!(out, "root = {}", hex::encode(ROOT)).unwrap();
        writeln!(out, "account = 0").unwrap();
        writeln!(out, "full_viewing_key = {}", hex::encode(fvk.to_bytes().as_ref())).unwrap();
        writeln!(out, "address = {}", fvk.address().encode()).unwrap();
        writeln!(out, "change_address = {}", fvk.change_address().encode()).unwrap();
        let decoded = QuanticAddress::decode_for(&fvk.address().encode(), network).unwrap();
        writeln!(out, "address.orchard = {}", hex::encode(decoded.orchard().to_raw_address_bytes())).unwrap();
        writeln!(out, "address.xwing_public_key.blake2b-256 = {}", hash(&decoded.xwing().to_bytes())).unwrap();
    }

    // A note envelope, to the regtest address of ROOT, with every input fixed.
    let sk = QuanticSpendingKey::from_root(&ROOT, Network::Regtest, 0).unwrap();
    let fvk = sk.full_viewing_key();
    let recipient = fvk.address();
    let rho_bytes = {
        let mut bytes = [0x11; 32];
        bytes[31] = 0x01;
        bytes
    };
    let rho: Rho = Option::from(Rho::from_bytes(&rho_bytes)).unwrap();
    let rseed: RandomSeed = Option::from(RandomSeed::from_bytes([0x22; 32], &rho)).unwrap();
    let value = NoteValue::from_raw(123_456_789);
    let note: Note =
        Option::from(Note::from_parts(*recipient.orchard(), value, rho, rseed, NoteVersion::V3)).unwrap();
    let cmx = ExtractedNoteCommitment::from(note.commitment());
    let rcv: ValueCommitTrapdoor = Option::from(ValueCommitTrapdoor::from_bytes([0x33; 32])).unwrap();
    let cv_net = ValueCommitment::derive(NoteValue::from_raw(0) - value, rcv);
    let mut memo = [0u8; MEMO_SIZE];
    memo[..24].copy_from_slice(b"Zoka Quantic test vector");
    let ovk = fvk.ovk(Scope::External);
    let envelope = encrypt_note(
        recipient.xwing(),
        &note,
        &memo,
        &cv_net,
        &cmx,
        Some(&ovk),
        &mut StdRng::seed_from_u64(0),
    );
    writeln!(out, "\n[envelope.regtest]").unwrap();
    writeln!(out, "recipient = keys.regtest.address").unwrap();
    writeln!(out, "value = 123456789").unwrap();
    writeln!(out, "rho = nf = {}", hex::encode(rho_bytes)).unwrap();
    writeln!(out, "rseed = {}", hex::encode([0x22; 32])).unwrap();
    writeln!(out, "rcv = {}", hex::encode([0x33; 32])).unwrap();
    writeln!(out, "memo = \"Zoka Quantic test vector\" followed by zeros").unwrap();
    writeln!(out, "ovk = external outgoing viewing key of keys.regtest").unwrap();
    writeln!(out, "cmx = {}", hex::encode(cmx.to_bytes())).unwrap();
    writeln!(out, "cv_net = {}", hex::encode(cv_net.to_bytes())).unwrap();
    writeln!(out, "kem = {}", hex::encode(envelope.kem_ciphertext())).unwrap();
    writeln!(out, "enc = {}", hex::encode(envelope.enc_ciphertext())).unwrap();
    writeln!(out, "out = {}", hex::encode(envelope.out_ciphertext())).unwrap();
    // The recipient finds exactly that note.
    let nf: Nullifier = Option::from(Nullifier::from_bytes(&rho_bytes)).unwrap();
    let found = try_note_decryption(&fvk, &nf, &cmx, &envelope).expect("the recipient decrypts it");
    assert_eq!(found.note, note);
    assert_eq!(found.memo, memo);

    // The genesis coinbase of a regtest chain with the premine to keys.regtest.
    let pk = proving_key();
    let build = || {
        build_coinbase(Network::Regtest, 0, &recipient, PREMINE_ATOMS, true, &pk, &mut StdRng::seed_from_u64(2026))
            .unwrap()
    };
    let coinbase = build();
    assert_eq!(coinbase.to_bytes(), build().to_bytes(), "a seeded build is reproducible");
    writeln!(out, "\n[coinbase.regtest]").unwrap();
    writeln!(out, "builder = build_coinbase(regtest, height 0, keys.regtest.address, 5000000000000, public, StdRng::seed_from_u64(2026))").unwrap();
    writeln!(out, "bytes.len = {}", coinbase.to_bytes().len()).unwrap();
    writeln!(out, "bytes.blake2b-256 = {}", hash(&coinbase.to_bytes())).unwrap();
    writeln!(out, "txid = {}", coinbase.txid().to_hex()).unwrap();
    writeln!(out, "auth_digest = {}", hex::encode(coinbase.auth_digest())).unwrap();
    out
}

#[test]
fn the_formats_give_the_published_vectors() {
    let generated = generate();
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(VECTORS);
    if std::env::var_os("ZOKA_WRITE_VECTORS").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &generated).unwrap();
        return;
    }
    let expected = std::fs::read_to_string(&path)
        .unwrap_or_else(|_| panic!("{VECTORS} is missing; generate it with ZOKA_WRITE_VECTORS=1"))
        .replace("\r\n", "\n");
    for (line, (want, got)) in expected.lines().zip(generated.lines()).enumerate() {
        assert_eq!(got, want, "line {} of {VECTORS} changed", line + 1);
    }
    assert_eq!(generated.lines().count(), expected.lines().count(), "{VECTORS} has another length");
}
